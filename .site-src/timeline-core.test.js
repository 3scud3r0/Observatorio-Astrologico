'use strict';
const assert=require('node:assert/strict');
const T=require('./timeline-core.js');
assert.equal(T.parseUTC('2024-02-29','23:59').toISOString(),'2024-02-29T23:59:00.000Z');
assert.throws(()=>T.parseUTC('2025-02-29','10:00'),/inexistente/);
assert.throws(()=>T.parseUTC('2024-02-29','25:10'),/hora UTC/);
const jan=T.parseUTC('2024-01-31','12:34');
assert.equal(T.advance(jan,1,'month').toISOString(),'2024-02-29T12:34:00.000Z');
assert.equal(T.advance(jan,1,'year').toISOString(),'2025-01-31T12:34:00.000Z');
assert.equal(T.advance(T.parseUTC('2024-02-29','12:00'),1,'year').toISOString(),'2025-02-28T12:00:00.000Z');
assert.equal(T.advance(jan,-1,'day').toISOString(),'2024-01-30T12:34:00.000Z');
assert.equal(T.advance(jan,1,'minute').toISOString(),'2024-01-31T12:35:00.000Z');
assert.equal(T.advance(jan,1,'hour').toISOString(),'2024-01-31T13:34:00.000Z');
assert.throws(()=>T.advance(jan,1,'century'),/desconhecida/);
assert.equal(T.julian(T.parseUTC('2000-01-01','12:00')),2451545);
assert.equal(T.separation(359,1),2);
const result=T.aspects(359,1,[{angle:0,orb:2},{angle:90,orb:1}]);
assert.equal(result[0].inOrb,true);
assert.equal(result[1].inOrb,false);
assert.throws(()=>T.aspects(0,90,[{angle:90,orb:-1}]),/Orbe inválido/);
console.log('UTC predictive clock tests: OK');
